//! Job definitions and the records that travel through a backend.

use std::time::Duration;

use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};

use crate::backoff::Backoff;
use crate::error::{Error, JobError};
use crate::util::{BoxFuture, duration_ms};

/// The queue jobs go to unless told otherwise.
pub const DEFAULT_QUEUE: &str = "default";

/// Longest accepted job name and queue name, in bytes.
pub const MAX_NAME_LEN: usize = 128;

/// Longest accepted unique / idempotency key, in bytes. Derive the key from
/// a digest when it is built from unbounded input.
pub const MAX_UNIQUE_KEY_LEN: usize = 512;

/// Size limit of a serialised job input unless
/// [`JobClient::max_payload_bytes`](crate::JobClient::max_payload_bytes) says otherwise: 1 MiB.
pub const DEFAULT_MAX_PAYLOAD_BYTES: usize = 1024 * 1024;

/// How much of an error message is stored with a job (and kept as a cron
/// task's last error), in bytes.
pub const MAX_ERROR_LEN: usize = 4096;

/// Highest and lowest accepted priority.
pub const MAX_PRIORITY: i8 = 100;
pub const MIN_PRIORITY: i8 = -100;

/// A unit of background work. Usually generated by `#[job]`:
///
/// ```ignore
/// #[job(queue = "mail", max_attempts = 5, timeout = "30s")]
/// async fn send_welcome(input: Welcome) -> Result<(), JobError> { /* ... */ }
/// ```
///
/// Implement it by hand for full control:
///
/// ```
/// use next_rust_jobs::{Job, JobContext, JobError, JobOptions};
///
/// struct Resize;
/// impl Job for Resize {
///     type Input = String;
///     const NAME: &'static str = "resize";
///     fn options() -> JobOptions { JobOptions::new().queue("images").max_attempts(3) }
///     async fn run(path: String, _ctx: JobContext) -> Result<(), JobError> {
///         println!("resizing {path}");
///         Ok(())
///     }
/// }
/// ```
pub trait Job: Send + Sync + 'static {
    type Input: Serialize + DeserializeOwned + Send + 'static;

    /// The name stored with every queued job. It must be unique in the
    /// application and **stable across deployments**: renaming it orphans
    /// jobs that are already queued.
    const NAME: &'static str;

    /// Defaults for this job; each can be overridden per enqueue.
    fn options() -> JobOptions {
        JobOptions::default()
    }

    fn run(input: Self::Input, ctx: JobContext) -> impl Future<Output = Result<(), JobError>> + Send;
}

/// A scheduled task. Usually generated by `#[cron("…")]`.
pub trait CronTask: Send + Sync + 'static {
    const NAME: &'static str;
    /// See [`crate::cron`] for the syntax.
    const SCHEDULE: &'static str;

    fn run() -> impl Future<Output = Result<(), JobError>> + Send;
}

/// Retry, timeout and routing settings of a job.
#[derive(Debug, Clone, PartialEq)]
pub struct JobOptions {
    pub queue: String,
    /// Total attempts including the first (minimum 1). Default 5.
    pub max_attempts: u32,
    /// One attempt is cancelled and counted as failed after this long. Default 5 min.
    pub timeout: Duration,
    pub backoff: Backoff,
    /// `-100..=100`, higher runs first. Default 0.
    pub priority: i8,
}

impl Default for JobOptions {
    fn default() -> Self {
        JobOptions {
            queue: DEFAULT_QUEUE.to_owned(),
            max_attempts: 5,
            timeout: Duration::from_secs(300),
            backoff: Backoff::default(),
            priority: 0,
        }
    }
}

impl JobOptions {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn queue(mut self, queue: impl Into<String>) -> Self {
        self.queue = queue.into();
        self
    }

    pub fn max_attempts(mut self, n: u32) -> Self {
        self.max_attempts = n.max(1);
        self
    }

    pub fn timeout(mut self, timeout: Duration) -> Self {
        self.timeout = timeout;
        self
    }

    pub fn backoff(mut self, backoff: Backoff) -> Self {
        self.backoff = backoff;
        self
    }

    pub fn priority(mut self, priority: i8) -> Self {
        self.priority = priority.clamp(MIN_PRIORITY, MAX_PRIORITY);
        self
    }
}

/// A queued job as a backend stores it. Immutable once enqueued; the attempt
/// counter and last error live beside it (see [`ClaimedJob`], [`DeadJob`]).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct JobRecord {
    pub id: String,
    pub name: String,
    pub queue: String,
    pub payload: serde_json::Value,
    pub priority: i8,
    pub max_attempts: u32,
    pub timeout_ms: u64,
    pub backoff: Backoff,
    /// See [`Enqueue::unique`](crate::Enqueue::unique).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub unique_key: Option<String>,
    /// `Some`: the key outlives the job by staying reserved this long after
    /// the enqueue (an idempotency window). `None`: released when the job
    /// completes or is dead-lettered.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub unique_ttl_ms: Option<u64>,
    pub enqueued_at_ms: u64,
    pub run_at_ms: u64,
}

/// Names end up in backend keys, log lines and the status report: refuse
/// what cannot be a deliberate name.
pub(crate) fn check_name(what: &str, value: &str, max: usize) -> Result<(), Error> {
    if value.is_empty() {
        return Err(Error::Invalid(format!("the {what} is empty")));
    }
    if value.len() > max {
        return Err(Error::Invalid(format!("the {what} is {} bytes long, the limit is {max}", value.len())));
    }
    if value.chars().any(char::is_control) {
        return Err(Error::Invalid(format!("the {what} contains a control character")));
    }
    Ok(())
}

impl JobRecord {
    /// What every backend checks before it stores a record: the job name,
    /// the queue name and the unique key are not empty, not oversized
    /// ([`MAX_NAME_LEN`], [`MAX_UNIQUE_KEY_LEN`]) and free of control
    /// characters. Custom backends should call it from `enqueue`.
    pub fn validate(&self) -> Result<(), Error> {
        check_name("job id", &self.id, MAX_NAME_LEN)?;
        check_name("job name", &self.name, MAX_NAME_LEN)?;
        check_name("queue name", &self.queue, MAX_NAME_LEN)?;
        if let Some(key) = &self.unique_key {
            check_name("unique key", key, MAX_UNIQUE_KEY_LEN)?;
        }
        Ok(())
    }

    pub(crate) fn from_options(name: &str, payload: serde_json::Value, o: JobOptions, now: u64) -> Self {
        JobRecord {
            id: crate::util::new_id(),
            name: name.to_owned(),
            queue: o.queue,
            payload,
            priority: o.priority.clamp(MIN_PRIORITY, MAX_PRIORITY),
            max_attempts: o.max_attempts.max(1),
            timeout_ms: duration_ms(o.timeout),
            backoff: o.backoff,
            unique_key: None,
            unique_ttl_ms: None,
            enqueued_at_ms: now,
            run_at_ms: now,
        }
    }
}

/// A job a worker holds. `token` proves ownership: a backend ignores
/// heartbeats and acknowledgements carrying a stale token, so a worker whose
/// claim expired cannot disturb the worker that took over.
#[derive(Debug, Clone, PartialEq)]
pub struct ClaimedJob {
    pub record: JobRecord,
    /// 1 for the first attempt.
    pub attempt: u32,
    pub token: String,
}

/// An entry of the dead-letter list.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DeadJob {
    pub record: JobRecord,
    pub attempts: u32,
    pub error: String,
    pub failed_at_ms: u64,
}

/// Passed to a job function that asks for it as a second argument.
#[derive(Debug, Clone)]
pub struct JobContext {
    pub id: String,
    pub name: String,
    pub queue: String,
    /// 1 for the first attempt.
    pub attempt: u32,
    pub max_attempts: u32,
    pub enqueued_at_ms: u64,
}

impl JobContext {
    /// Whether a failure of this attempt sends the job to the dead-letter list.
    pub fn is_last_attempt(&self) -> bool {
        self.attempt >= self.max_attempts
    }
}

pub(crate) type Handler =
    std::sync::Arc<dyn Fn(serde_json::Value, JobContext) -> BoxFuture<'static, Result<(), JobError>> + Send + Sync>;

pub(crate) fn handler_of<J: Job>() -> Handler {
    std::sync::Arc::new(|payload, ctx| {
        Box::pin(async move {
            // Input that does not deserialise will not deserialise next time either.
            let input: J::Input = serde_json::from_value(payload)
                .map_err(|e| JobError::fatal(format!("invalid input for job `{}`: {e}", J::NAME)))?;
            J::run(input, ctx).await
        })
    })
}
